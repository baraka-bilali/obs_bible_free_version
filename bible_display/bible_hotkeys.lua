--[[
      OBS Studio Lua script : Control Bible verses display with hotkeys
      Adapted from: Animated-Lower-Thirds project
      Version: 2.0

      How it works:
      Each hotkey press increments a counter. Counters are written to
      common/js/hotkeys.js, which the control panel polls. The panel reacts
      to every counter change (so repeated presses are never lost).
      The panel must be open (ideally as an OBS custom browser dock).
--]]


local obs = obslua
local debug = false
local hk = {}

-- Ordered list of actions: { id, label }
local ACTIONS = {
	{ "DISPLAY_VERSE", "Bible: Show / Hide Verse" },
	{ "HIDE_VERSE",    "Bible: Hide Verse" },
	{ "SLOT_01", "Bible: Show Favorite #1" },
	{ "SLOT_02", "Bible: Show Favorite #2" },
	{ "SLOT_03", "Bible: Show Favorite #3" },
	{ "SLOT_04", "Bible: Show Favorite #4" },
	{ "SLOT_05", "Bible: Show Favorite #5" },
	{ "SLOT_06", "Bible: Show Favorite #6" },
	{ "SLOT_07", "Bible: Show Favorite #7" },
	{ "SLOT_08", "Bible: Show Favorite #8" },
	{ "SLOT_09", "Bible: Show Favorite #9" },
	{ "SLOT_10", "Bible: Show Favorite #10" },
}

-- Press counters (reset when the script is (re)loaded; the session id lets
-- the control panel detect the reset instead of treating it as a press)
local counters = {}
local session = tostring(os.time())

-- Write the current state to the JS file read by the control panel
local function write_hotkeys_js()
	local path = script_path() .. '../common/js/hotkeys.js'
	local output, err = io.open(path, "w")
	if not output then
		obs.script_log(obs.LOG_WARNING, "Cannot write " .. path .. ": " .. tostring(err))
		return
	end

	local parts = {}
	for _, action in ipairs(ACTIONS) do
		local id = action[1]
		table.insert(parts, string.format('%s: %d', id, counters[id] or 0))
	end

	output:write('// Auto-generated by bible_hotkeys.lua - do not edit\n')
	output:write('window.BIBLE_HOTKEYS = { session: "' .. session .. '", counters: { ' .. table.concat(parts, ', ') .. ' } };\n')
	output:close()
end

local function on_hotkey(id)
	counters[id] = (counters[id] or 0) + 1
	if debug then obs.script_log(obs.LOG_INFO, string.format("Hotkey: %s (#%d)", id, counters[id])) end
	write_hotkeys_js()
end

----------------------------------------------------------

-- Called on startup
function script_load(settings)
	for _, action in ipairs(ACTIONS) do
		local id, label = action[1], action[2]
		counters[id] = 0
		hk[id] = obs.obs_hotkey_register_frontend(id, label, function(pressed)
			if pressed then on_hotkey(id) end
		end)
		local hotkeyArray = obs.obs_data_get_array(settings, id)
		obs.obs_hotkey_load(hk[id], hotkeyArray)
		obs.obs_data_array_release(hotkeyArray)
	end
	write_hotkeys_js()
end


-- Called on unload
function script_unload()
end


-- Called when settings changed
function script_update(settings)
	debug = obs.obs_data_get_bool(settings, "debug")
end


-- Return description shown to user
function script_description()
	return "Control the display of Bible verses with hotkeys.\n" ..
		"Requires the control panel to be open (recommended: as a custom browser dock).\n" ..
		"Favorite slots #1-#10 show the favorites of the List tab, in order."
end


-- Define properties that user can change
function script_properties()
	local props = obs.obs_properties_create()
	obs.obs_properties_add_bool(props, "debug", "Debug")
	return props
end


-- Set default values
function script_defaults(settings)
	obs.obs_data_set_default_bool(settings, "debug", false)
end


-- Save additional data not set by user
function script_save(settings)
	for _, action in ipairs(ACTIONS) do
		local id = action[1]
		if hk[id] then
			local hotkeyArray = obs.obs_hotkey_save(hk[id])
			obs.obs_data_set_array(settings, id, hotkeyArray)
			obs.obs_data_array_release(hotkeyArray)
		end
	end
end
